class AnalysisDecision(StrictSchema):
    status: Literal[
        "needs_clarification",
        "ready",
    ]

    question: str | None = Field(
        default=None,
        min_length=1,
        max_length=1_000,
        description=(
            "A focused question for the user when status is "
            "'needs_clarification'."
        ),
    )

    options: list[ClarificationOption] = Field(
        default_factory=list,
        max_length=10,
    )

    plan: AnalysisPlan | None = Field(
        default=None,
        description=(
            "The validated chart or KPI plan when status is 'ready'."
        ),
    )

    @model_validator(mode="after")
    def validate_decision(self) -> "AnalysisDecision":
        if self.status == "needs_clarification":
            if self.question is None:
                raise ValueError(
                    "A clarification decision requires a question."
                )

            if self.plan is not None:
                raise ValueError(
                    "A clarification decision cannot contain an "
                    "analysis plan."
                )

        if self.status == "ready":
            if self.plan is None:
                raise ValueError(
                    "A ready decision requires an analysis plan."
                )

            if self.question is not None:
                raise ValueError(
                    "A ready decision cannot contain a clarification "
                    "question."
                )

            if self.options:
                raise ValueError(
                    "A ready decision cannot contain clarification "
                    "options."
                )

        return self

