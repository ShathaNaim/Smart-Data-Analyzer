from __future__ import annotations

from typing import Annotated, Literal, TypeAlias

from pydantic import BaseModel, ConfigDict, Field, model_validator


# ---------------------------------------------------------------------------
# Shared configuration
# ---------------------------------------------------------------------------

class StrictSchema(BaseModel):
    """
    Reject fields that are not explicitly defined in the schema.

    This helps prevent the AI or frontend from silently sending unsupported
    chart and analysis settings.
    """

    model_config = ConfigDict(extra="forbid")


# ---------------------------------------------------------------------------
# Conversation request schemas
# ---------------------------------------------------------------------------

class ConversationMessage(StrictSchema):
    role: Literal["user", "assistant"]
    content: str = Field(min_length=1, max_length=4_000)


class QuestionRequest(StrictSchema):
    question: str = Field(
        min_length=1,
        max_length=2_000,
        description="The user's latest question or clarification answer.",
    )

    conversation_id: str | None = Field(
        default=None,
        max_length=100,
        description="Identifier used to connect clarification turns.",
    )

    history: list[ConversationMessage] = Field(
        default_factory=list,
        max_length=10,
        description="Recent conversation messages needed to interpret the request.",
    )


