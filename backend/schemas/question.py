class FilterCondition(StrictSchema):
    column: str = Field(min_length=1, max_length=200)

    operator: Literal[
        "eq",
        "ne",
        "gt",
        "gte",
        "lt",
        "lte",
        "contains",
        "in",
        "between",
        "is_null",
        "is_not_null",
    ]

    # The executor will validate the value against the actual column type.
    value: str | int | float | bool | list[str | int | float] | None = None


class DimensionSpec(StrictSchema):
    column: str = Field(min_length=1, max_length=200)

    alias: str = Field(min_length=1, max_length=200)

    time_granularity: Literal[
        "day",
        "week",
        "month",
        "quarter",
        "year",
    ] | None = None


class MeasureSpec(StrictSchema):
    column: str = Field(min_length=1, max_length=200)

    aggregation: Literal[
        "none",
        "sum",
        "mean",
        "median",
        "min",
        "max",
        "count",
        "nunique",
    ]

    alias: str = Field(min_length=1, max_length=200)


class SortSpec(StrictSchema):
    column: str = Field(min_length=1, max_length=200)
    direction: Literal["asc", "desc"] = "asc"


class ChartAnalysisPlan(StrictSchema):
    """
    A declarative chart plan generated by the AI.

    The plan describes a grouped calculation and its visualization.
    It never contains executable Python, SQL, or JavaScript code.
    """

    output_type: Literal["chart"] = "chart"

    intent: str = Field(
        min_length=1,
        max_length=1_000,
        description="Short explanation of what the chart will calculate.",
    )

    dimensions: list[DimensionSpec] = Field(
        min_length=1,
        max_length=3,
    )

    measures: list[MeasureSpec] = Field(
        min_length=0,
        max_length=5,
    )

    filters: list[FilterCondition] = Field(
        default_factory=list,
        max_length=20,
    )

    sort: list[SortSpec] = Field(
        default_factory=list,
        max_length=5,
    )

    row_limit: int = Field(
        default=100,
        ge=1,
        le=1_000,
    )

    chart_type: Literal[
        "scatter",
        "histogram",
        "line",
        "bar",
        "area",
        "pie",
        "donut",
        "horizontal_bar",
    ]

    assumptions: list[str] = Field(
        default_factory=list,
        max_length=10,
    )

    bin_count: int | None = Field(default=None, ge=2, le=50)

    @model_validator(mode="after")
    def validate_chart_requirements(
        self,
    ) -> "ChartAnalysisPlan":
        if self.chart_type in {"scatter", "histogram"}:
            if self.dimensions[0].time_granularity is not None or self.sort:
                raise ValueError("Scatter and histogram charts do not support date grouping or sorting.")
        if self.chart_type == "histogram":
            if self.row_limit < 2:
                raise ValueError("Histograms require room for at least two bins.")
            if self.measures:
                raise ValueError("Histograms require one numeric dimension and no measures.")
            if self.bin_count is not None and self.bin_count > self.row_limit:
                raise ValueError("Histogram bin count must not exceed row_limit.")
        else:
            if self.bin_count is not None:
                raise ValueError("Only histograms support bin_count.")
            if not self.measures:
                raise ValueError("This chart requires a measure.")
            if self.chart_type == "scatter":
                if self.row_limit < 2:
                    raise ValueError("Scatter plots require a point limit of at least two.")
                if len(self.measures) != 1 or self.measures[0].aggregation != "none":
                    raise ValueError("Scatter requires one unaggregated measure (aggregation: none).")
            elif any(measure.aggregation == "none" for measure in self.measures):
                raise ValueError("Grouped charts require an aggregation.")

        if len(self.dimensions) != 1:
            raise ValueError(
                "The current chart implementation requires exactly one "
                "dimension."
            )

        if self.chart_type in {"pie", "donut"} and len(self.measures) != 1:
            raise ValueError(
                "Pie and doughnut charts require exactly one measure."
            )

        return self


class KpiAnalysisPlan(StrictSchema):
    """
    A declarative KPI plan generated by the AI.

    A KPI performs one aggregation and returns one numeric value.
    It does not group results by a dimension.
    """

    output_type: Literal["kpi"] = "kpi"

    intent: str = Field(
        min_length=1,
        max_length=1_000,
        description="Short explanation of what the KPI will calculate.",
    )

    title: str = Field(
        min_length=1,
        max_length=300,
        description="Short user-facing title for the KPI card.",
    )

    description: str | None = Field(
        default=None,
        max_length=500,
        description="Optional supporting text displayed on the KPI card.",
    )

    measure: MeasureSpec = Field(
        description="The single aggregation used to calculate the KPI value.",
    )

    filters: list[FilterCondition] = Field(
        default_factory=list,
        max_length=20,
    )

    format: Literal[
        "number",
        "integer",
        "currency",
        "percent",
    ] = "number"

    currency: str | None = Field(
        default=None,
        min_length=3,
        max_length=3,
        description="ISO currency code such as USD or JOD.",
    )

    assumptions: list[str] = Field(
        default_factory=list,
        max_length=10,
    )

    @model_validator(mode="after")
    def validate_kpi_format(
        self,
    ) -> "KpiAnalysisPlan":
        if self.measure.aggregation == "none":
            raise ValueError("KPI calculations require an aggregation.")
        if self.format == "currency" and self.currency is None:
            raise ValueError(
                "A currency KPI must include a currency code."
            )

        if self.format != "currency" and self.currency is not None:
            raise ValueError(
                "Currency can only be provided when the KPI format "
                "is 'currency'."
            )

        return self


AnalysisPlan: TypeAlias = (
    ChartAnalysisPlan | KpiAnalysisPlan
)


